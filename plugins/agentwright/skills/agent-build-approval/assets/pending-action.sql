-- pending_action: one row per gated write tool call that waits for a person.
-- A starting schema in portable SQL. It has not been run against any database.
-- Adapt the types to your engine (for example TIMESTAMP WITH TIME ZONE, JSON or JSONB for the JSON columns).
-- Every query filters by tenant_id; a row from another tenant must never be read, approved or run.

CREATE TABLE pending_action (
  id               VARCHAR(64)  NOT NULL PRIMARY KEY,  -- generated by your code when the run pauses
  tenant_id        VARCHAR(64)  NOT NULL,              -- copied from the verified event, never from model output
  thread_id        VARCHAR(255) NOT NULL,              -- the conversation this run belongs to
  run_id           VARCHAR(64)  NOT NULL,              -- the run that paused
  tool_call_id     VARCHAR(255) NOT NULL,              -- the id the model gave the call; its one tool result must carry it
  tool_name        VARCHAR(128) NOT NULL,
  tool_input       TEXT         NOT NULL,              -- JSON; the write runs with exactly these arguments
  other_results    TEXT         NULL,                  -- JSON list of tool results for the other calls in the same model response
  preview          TEXT         NOT NULL,              -- what the person was shown, rendered by code from tool_input
  requested_by     VARCHAR(255) NULL,                  -- the person whose message started the run
  ask_ref          VARCHAR(32)  NOT NULL,              -- short reference that keys the question's thread
  ask_message_id   VARCHAR(255) NULL,                  -- the channel's id for the posted question; NULL until posted
  reminded_at      TIMESTAMP    NULL,                  -- set by the one reminder; NULL means none sent yet
  status           VARCHAR(32)  NOT NULL DEFAULT 'awaiting_approval',
  expires_at       TIMESTAMP    NOT NULL,              -- the approval window; set per tool, see SKILL.md
  decided_by       VARCHAR(255) NULL,                  -- the verified approver or decliner; NULL for expiry or supersede
  decided_at       TIMESTAMP    NULL,
  decision_reason  TEXT         NULL,                  -- the decline reason, or 'superseded by a new message'
  idempotency_key  VARCHAR(128) NOT NULL,              -- sent with the write; replaced only when a definite failure reopens the row
  posting_since    TIMESTAMP    NULL,                  -- when the current write attempt started; the sweeper reads it
  result           TEXT         NULL,                  -- the content of the one tool result for tool_call_id
  last_error       TEXT         NULL,                  -- the latest definite failure, shown to the person
  created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT pending_action_status_valid
    CHECK (status IN ('awaiting_approval', 'posting', 'posted', 'declined', 'expired')),
  -- A finished row always holds the tool result it sent back.
  CONSTRAINT pending_action_result_when_finished
    CHECK (status IN ('awaiting_approval', 'posting') OR result IS NOT NULL),
  CONSTRAINT pending_action_posting_has_start
    CHECK (status <> 'posting' OR posting_since IS NOT NULL),
  -- A rerun of the same pause cannot create a second row for the same call.
  CONSTRAINT pending_action_one_row_per_call UNIQUE (tenant_id, run_id, tool_call_id),
  CONSTRAINT pending_action_ref_unique UNIQUE (tenant_id, ask_ref),
  CONSTRAINT pending_action_key_unique UNIQUE (idempotency_key)
);

-- At most one open action per thread. Partial indexes exist in PostgreSQL and SQLite, not in MySQL;
-- on MySQL, enforce it with a nullable generated column that holds thread_id only while the row is open.
CREATE UNIQUE INDEX pending_action_one_open_per_thread
  ON pending_action (tenant_id, thread_id)
  WHERE status IN ('awaiting_approval', 'posting');

-- The sweeper's two queries: rows to expire, and write attempts that stopped without an outcome.
CREATE INDEX pending_action_sweep ON pending_action (status, expires_at, posting_since);

